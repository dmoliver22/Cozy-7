import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
const exe = '/opt/pw-browsers/' + readdirSync('/opt/pw-browsers').find((d) => d.startsWith('chromium-')) + '/chrome-linux/chrome';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1360, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://127.0.0.1:4321/quiz/', { waitUntil: 'networkidle' });
await page.click('button.opt[data-slug="tinnitus"]');
await page.click('button.opt[data-tried="nothing"]');
await page.waitForSelector('#result h2');
console.log('result h2:', await page.textContent('#result h2'));
console.log('result links:', await page.$$eval('#result a', (as) => as.map((a) => a.getAttribute('href'))));
await page.screenshot({ path: 'qa/quiz-result.png' });
// theme toggle + mobile menu
await page.click('#theme-btn');
console.log('theme attr:', await page.evaluate(() => document.documentElement.getAttribute('data-theme')));
const m = await browser.newPage({ viewport: { width: 390, height: 844 } });
await m.goto('http://127.0.0.1:4321/', { waitUntil: 'networkidle' });
await m.screenshot({ path: 'qa/home-mobile-viewport.png' });
await m.click('#menu-btn');
await m.screenshot({ path: 'qa/home-mobile-menu.png' });
await m.goto('http://127.0.0.1:4321/oxytocin-for/tinnitus/', { waitUntil: 'networkidle' });
await m.screenshot({ path: 'qa/tinnitus-mobile-viewport.png' });
const hasHScroll = await m.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
console.log('mobile horizontal scroll on tinnitus page:', hasHScroll);
console.log('JS errors:', errors.length ? errors : 'none');
await browser.close();
